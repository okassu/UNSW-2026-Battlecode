"""Write tools/variants.txt from snapshots/var/: one line per param variant, machine-independent.

    python3 tools/mkvariants.py

A line is `NAME SNAPSHOT [KEY=VALUE ...]`, e.g. `v11u v11 MAPLIB=0`. tools/setup_pc.sh rebuilds each SNAPSHOT
(snapshots/SNAPSHOT) and recreates every variant from this file, so the list travels with the repo while the
variant scripts themselves (absolute paths) are rebuilt on each machine. Variants whose binary is not a snapshot
build (old scratchpad bots) are skipped and listed on stderr.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
out, skipped = [], []
for f in sorted((ROOT / "snapshots" / "var").iterdir()):
    if not f.is_file():
        continue
    env, snap = [], None
    for line in f.read_text().splitlines():
        line = line.strip()
        if line.startswith("export "):
            env += line[len("export "):].split()
        elif line.startswith("exec "):
            m = re.search(r"snapshots/([^/]+)/\.unswbc-build/bot", line)
            snap = m[1] if m else None
    if snap and (ROOT / "snapshots" / snap / "main.cpp").exists():
        out.append(" ".join([f.name, snap] + env))
    else:
        skipped.append(f.name)
(ROOT / "tools" / "variants.txt").write_text(
    "# NAME SNAPSHOT [KEY=VALUE ...]  (generated by tools/mkvariants.py; tools/setup_pc.sh rebuilds these)\n"
    + "\n".join(out) + "\n")
print(f"{len(out)} variants -> tools/variants.txt")
if skipped:
    print(f"skipped {len(skipped)} (binary not in snapshots/): {' '.join(skipped)}", file=sys.stderr)
