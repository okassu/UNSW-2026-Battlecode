"""Generate mybot/maplib.hpp from maps/*.map.

Every dragon starts with no memory, so a freshly split child knows nothing about
the walls around it. Embedding the known maps lets a dragon recognise the map
from its first 7x7 view and plan with every wall, portal and spawn rate.

    python3 tools/gen_maplib.py            # rewrites mybot/maplib.hpp
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = [(0, -1), (1, 0), (0, 1), (-1, 0)]  # N E S W


def load(path: pathlib.Path):
    W = H = 0
    name = path.stem
    sym = ""
    gaps: dict[tuple[int, int], tuple[int, int]] = {}
    edges: dict[int, tuple[int, int]] = {}
    for line in path.read_text().splitlines():
        t = line.split()
        if not t:
            continue
        if t[0] == "MAP":
            W, H = int(t[1]), int(t[2])
        elif t[0] == "SYMMETRY":
            sym = t[1]
        elif t[0] == "TILE":
            gaps[(int(t[1]), int(t[2]))] = (int(t[3]), int(t[4]))
        elif t[0] == "EDGE":
            edges[int(t[1])] = (int(t[2]), int(t[3]))
    return name, W, H, sym, gaps, edges


def build(path: pathlib.Path):
    name, W, H, sym, gaps, edges = load(path)
    kelp = [0] * (W * H)
    portal = [0] * (W * H)
    portal_edges: list[tuple[int, int, int]] = []  # tile, dir, id (one side only)

    def mark(tile_a: int, dir_a: int, kind: int, pid: int) -> None:
        # edge on side dir_a of tile_a; mirror onto the neighbour
        x, y = tile_a % W, tile_a // W
        dx, dy = DIRS[dir_a]
        b = ((y + dy) % H) * W + (x + dx) % W
        dir_b = (dir_a + 2) % 4
        if kind == 1:
            kelp[tile_a] |= 1 << dir_a
            kelp[b] |= 1 << dir_b
        elif kind == 2:
            portal[tile_a] |= 1 << dir_a
            portal[b] |= 1 << dir_b
            portal_edges.append((tile_a, dir_a, pid))

    for index, (kind, pid) in edges.items():
        if kind == 0:
            continue
        row, col = divmod(index, W + 1)
        if row % 2 == 0:  # horizontal: north side of tile row row/2
            y = row // 2
            if col >= W:
                continue
            if y == H:  # south border == north of row 0
                mark(((H - 1) * W) + col, 2, kind, pid)
            else:
                mark(y * W + col, 0, kind, pid)
        else:  # vertical: west side of tile col in row (row-1)/2
            y = (row - 1) // 2
            if col == W:
                mark(y * W + W - 1, 1, kind, pid)
            else:
                mark(y * W + col, 3, kind, pid)

    palette: list[tuple[int, int]] = []
    gap_idx = []
    for y in range(H):
        for x in range(W):
            g = gaps.get((x, y), (0, 0))
            if g not in palette:
                palette.append(g)
            gap_idx.append(palette.index(g))
    if len(palette) > 62:
        raise SystemExit(f"{name}: too many distinct gaps")
    alphabet = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
    return {
        "name": name, "W": W, "H": H, "sym": sym,
        "kelp": "".join("0123456789abcdef"[k] for k in kelp),
        "portal": "".join("0123456789abcdef"[p] for p in portal),
        "portals": portal_edges,
        "palette": palette,
        "gaps": "".join(alphabet[i] for i in gap_idx),
    }


def main() -> None:
    maps = sorted((ROOT / "maps").glob("*.map"))
    out = [
        "// Generated by tools/gen_maplib.py from maps/*.map -- do not edit by hand.",
        "#pragma once",
        "",
        "namespace maplib {",
        "",
        "struct PortalEdge { int tile, dir, id; };",
        "struct GapRange { int lo, hi; };",
        "struct MapInfo {",
        "    char const* name;",
        "    int w, h;",
        "    char const* kelp;   // hex digit per tile: kelp bits N=1 E=2 S=4 W=8",
        "    char const* portal; // hex digit per tile: portal bits",
        "    PortalEdge const* portals;",
        "    int portalCount;",
        "    GapRange const* palette;",
        "    char const* gaps;   // palette index per tile, base62",
        "};",
        "",
    ]
    entries = []
    for i, path in enumerate(maps):
        m = build(path)
        pe = ", ".join(f"{{{t},{d},{p}}}" for t, d, p in m["portals"]) or "{0,0,-1}"
        pal = ", ".join(f"{{{lo},{hi}}}" for lo, hi in m["palette"])
        out.append(f"inline constexpr PortalEdge portals{i}[] = {{{pe}}};")
        out.append(f"inline constexpr GapRange palette{i}[] = {{{pal}}};")
        entries.append(
            f'    {{"{m["name"]}", {m["W"]}, {m["H"]},\n     "{m["kelp"]}",\n     "{m["portal"]}",\n'
            f'     portals{i}, {len(m["portals"])}, palette{i},\n     "{m["gaps"]}"}},'
        )
    out.append("")
    out.append("inline constexpr MapInfo maps[] = {")
    out.extend(entries)
    out.append("};")
    out.append(f"inline constexpr int mapCount = {len(maps)};")
    out.append("")
    out.append("} // namespace maplib")
    target = ROOT / "mybot" / "maplib.hpp"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(maps)} maps, {target.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
